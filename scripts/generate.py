#!/usr/bin/env python3
"""Generate src/generated.rs from a Lucide release tarball or icons/ directory.

Usage:
  python3 scripts/generate.py --archive /tmp/lucide-1.34.0.tar.gz --version 1.34.0
  python3 scripts/generate.py --icons-dir /path/to/lucide/icons --version 1.34.0
"""

from __future__ import annotations

import argparse
import io
import re
import sys
import tarfile
from pathlib import Path

SVG_OPEN = re.compile(r"<svg\b[^>]*>", re.IGNORECASE | re.DOTALL)
RUST_KEYWORDS = {
    "Self",
    "abstract",
    "as",
    "async",
    "await",
    "become",
    "box",
    "break",
    "const",
    "continue",
    "crate",
    "do",
    "dyn",
    "else",
    "enum",
    "extern",
    "false",
    "final",
    "fn",
    "for",
    "if",
    "impl",
    "in",
    "let",
    "loop",
    "macro",
    "match",
    "mod",
    "move",
    "mut",
    "override",
    "priv",
    "pub",
    "ref",
    "return",
    "self",
    "static",
    "struct",
    "super",
    "trait",
    "true",
    "try",
    "type",
    "typeof",
    "unsafe",
    "unsized",
    "use",
    "virtual",
    "where",
    "while",
    "yield",
}


def pascal_case(kebab: str) -> str:
    parts = [p for p in kebab.split("-") if p]
    ident = "".join(p[:1].upper() + p[1:] for p in parts)
    if not ident:
        raise SystemExit(f"empty identifier from {kebab!r}")
    if ident[0].isdigit():
        ident = f"Icon{ident}"
    if ident in RUST_KEYWORDS:
        ident = f"{ident}_"
    return ident


def rust_raw_string(s: str) -> str:
    hashes = 0
    while True:
        closer = '"' + "#" * hashes
        if closer not in s:
            return "r" + "#" * hashes + '"' + s + closer
        hashes += 1


def extract_inner(svg_text: str, name: str) -> str:
    match = SVG_OPEN.search(svg_text)
    if match is None:
        raise SystemExit(f"{name}: missing <svg> root")
    rest = svg_text[match.end() :]
    end = rest.rfind("</svg>")
    if end < 0:
        raise SystemExit(f"{name}: missing </svg>")
    inner = rest[:end].strip()
    if not inner:
        raise SystemExit(f"{name}: empty SVG inner")
    if "<svg" in inner.lower():
        raise SystemExit(f"{name}: nested <svg> is not supported")
    return inner


def load_from_archive(archive: Path) -> list[tuple[str, str]]:
    icons: list[tuple[str, str]] = []
    with tarfile.open(archive, "r:gz") as tf:
        for member in tf.getmembers():
            name = member.name.replace("\\", "/")
            if not name.endswith(".svg"):
                continue
            parts = name.split("/")
            if len(parts) < 2 or parts[-2] != "icons":
                continue
            kebab = parts[-1][:-4]
            fileobj = tf.extractfile(member)
            if fileobj is None:
                continue
            text = fileobj.read().decode("utf-8")
            icons.append((kebab, extract_inner(text, kebab)))
    return icons


def load_from_dir(icons_dir: Path) -> list[tuple[str, str]]:
    icons: list[tuple[str, str]] = []
    for path in sorted(icons_dir.glob("*.svg")):
        kebab = path.stem
        text = path.read_text(encoding="utf-8")
        icons.append((kebab, extract_inner(text, kebab)))
    return icons


def emit_rs(version: str, icons: list[tuple[str, str]]) -> str:
    icons = sorted(icons, key=lambda item: item[0])
    variants: list[tuple[str, str, str]] = []
    used: dict[str, str] = {}
    for kebab, inner in icons:
        ident = pascal_case(kebab)
        if ident in used:
            raise SystemExit(
                f"PascalCase collision: {kebab} and {used[ident]} -> {ident}"
            )
        used[ident] = kebab
        variants.append((ident, kebab, inner))

    count = len(variants)
    out = io.StringIO()
    w = out.write
    w("// @generated by scripts/generate.py. Do not edit.\n")
    w(f"// Lucide {version} — {count} icons.\n")
    w("\n")
    w("/// Lucide release this crate was generated from.\n")
    w(f'pub const LUCIDE_VERSION: &str = "{version}";\n')
    w("\n")
    w("/// Number of icons in [`Lucide::ALL`].\n")
    w(f"pub const ICON_COUNT: usize = {count};\n")
    w("\n")
    w("/// Every Lucide icon shipped in this crate.\n")
    w("#[derive(Clone, Copy, Debug, Hash, PartialEq, Eq, PartialOrd, Ord)]\n")
    w("#[repr(u16)]\n")
    w("pub enum Lucide {\n")
    for i, (ident, kebab, _) in enumerate(variants):
        w(f"    /// `{kebab}`\n")
        w(f"    {ident} = {i},\n")
    w("}\n\n")

    w("impl Lucide {\n")
    w("    /// All icons in kebab-case sort order.\n")
    w(f"    pub const ALL: [Self; {count}] = [\n")
    for ident, _, _ in variants:
        w(f"        Self::{ident},\n")
    w("    ];\n")
    w("}\n\n")

    w(f"pub(crate) static NAMES: [&str; {count}] = [\n")
    for _, kebab, _ in variants:
        w(f"    {rust_raw_string(kebab)},\n")
    w("];\n\n")

    w(f"pub(crate) static INNERS: [&str; {count}] = [\n")
    for _, _, inner in variants:
        w(f"    {rust_raw_string(inner)},\n")
    w("];\n")
    return out.getvalue()


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--version", required=True)
    parser.add_argument("--archive", type=Path)
    parser.add_argument("--icons-dir", type=Path)
    parser.add_argument(
        "--out",
        type=Path,
        default=Path(__file__).resolve().parent.parent / "src" / "generated.rs",
    )
    args = parser.parse_args()
    if bool(args.archive) == bool(args.icons_dir):
        parser.error("provide exactly one of --archive or --icons-dir")

    if args.archive:
        icons = load_from_archive(args.archive)
    else:
        icons = load_from_dir(args.icons_dir)

    if not icons:
        raise SystemExit("no SVG icons found")

    text = emit_rs(args.version, icons)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text, encoding="utf-8")
    print(f"wrote {args.out} ({len(icons)} icons, {len(text)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
